def _clean(lines):
    """去掉行尾空白（那些行是为可读性折行写的）。"""
    return [line.rstrip() for line in lines]


def write_proc(root, tcp=None, tcp6=None):
    """在 ``root/net/`` 下写 tcp / tcp6。``None`` 表示**不创建该文件**。"""
    net = os.path.join(root, "net")
    os.makedirs(net, exist_ok=True)
    if tcp is not None:
        with open(os.path.join(net, "tcp"), "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(_clean(tcp.splitlines())) + "\n")
    if tcp6 is not None:
        with open(os.path.join(net, "tcp6"), "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(_clean(tcp6.splitlines())) + "\n")
    return net


def write_services(path, text=SERVICES_TEXT):
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return path


def default_proc(root):
    """写一份默认的假 /proc（tcp + tcp6），返回根目录。"""
    write_proc(root, tcp=DEFAULT_TCP, tcp6=DEFAULT_TCP6)
    return root
